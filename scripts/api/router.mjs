const UNIT = { token: "per token in and out", second: "per second of audio", character: "per character spoken", image: "per image" };

function usd(micro) {
  const dollars = micro / 1_000_000;
  return dollars >= 1 ? `$${dollars.toLocaleString("en-US", { maximumFractionDigits: 2 })}` : `$${dollars.toFixed(2)}`;
}

const sdkCall = (kind) => kind.gdscript.replace(/\s*->.*$/, "");
const kindPath = (kind) => kind.docs_slug;

function typeOf(schema) {
  if (!schema) return "any";
  if (schema.enum) return schema.enum.map((v) => code(v)).join(", ");
  if (schema.type === "array") return `array of ${schema.items?.type === "object" ? "objects" : (schema.items?.type ?? "any")}`;
  return Array.isArray(schema.type) ? schema.type.join(" or ") : (schema.type ?? "any");
}

function limits(schema) {
  const out = [];
  if (schema.minLength !== undefined || schema.maxLength !== undefined) out.push(`${schema.minLength ?? 0} to ${schema.maxLength} characters`);
  if (schema.minimum !== undefined && schema.maximum !== undefined) out.push(`${schema.minimum} to ${schema.maximum}`);
  if (schema.maxItems !== undefined) out.push(`up to ${schema.maxItems} items`);
  if (schema.maxProperties !== undefined) out.push(`up to ${schema.maxProperties} entries`);
  const id = /^\^\[A-Za-z0-9_-\]\{(\d+),(\d+)\}\$$/.exec(schema.pattern ?? "");
  if (id) out.push(`${id[1]} to ${id[2]} letters, digits, dashes or underscores; your game may choose it`);
  return out.join(", ");
}

/** The kind's either-or fields (anyOf / oneOf of required lists), as one plain line. */
function alternatives(kind) {
  const list = (key) => (kind.inputs?.[key] ?? []).map((choice) => (choice.required ?? []).map((name) => code(name)).join(" with "));
  const any = list("anyOf");
  const one = list("oneOf");
  if (any.length) return `Send ${any.join(", ")}, or both. With only ${code("tool_results")}, leave the text empty: it answers the previous turn's tool calls.`;
  if (one.length) return `Send ${one[0]}, or only ${one.slice(1).join(", or only ")} with an empty text.`;
  return "";
}

/** The kind's request fields a game sets (the SDK fills request_id). */
function inputRows(kind) {
  const props = kind.inputs?.properties ?? {};
  const required = new Set(kind.inputs?.required ?? []);
  return Object.entries(props)
    .filter(([name]) => name !== "request_id")
    .map(([name, s]) => `| ${code(name)}${required.has(name) ? " (required)" : ""} | ${cell(typeOf(s)).replace(/\\`/g, "`")} | ${name === "character" ? "The id of a character you made in Studio" : name === "exchange_id" ? "The exchange_id of a reply from the last hour" : cell([s.description, limits(s)].filter(Boolean).join(". ")) || (s.enum ? "One of these" : "Any")} |`);
}

const PRICE_UNIT = {
  input_tokens: ["input token", "input tokens"],
  output_tokens: ["output token", "output tokens"],
  characters: ["character", "characters"],
  audio_seconds: ["second of audio", "seconds of audio"],
  images: ["image", "images"],
  session_seconds: ["second of session", "seconds of session"],
};

/** "$0.15 per 1M input tokens" from {unit, per, usd}. */
function priceLine(price) {
  const [one, many] = PRICE_UNIT[price.unit] ?? [price.unit, price.unit];
  const per = price.per === 1 ? one : `${price.per >= 1_000_000 && price.per % 1_000_000 === 0 ? `${price.per / 1_000_000}M` : price.per.toLocaleString("en-US")} ${many}`;
  if (!/^\d+(\.\d+)?$/.test(price.usd)) throw new Error(`router price ${JSON.stringify(price.usd)} is not a USD decimal string`);
  return `$${price.usd} per ${per}`;
}

/** The Models and prices page, from the public price list (GET /v1/router/models). */
function renderRouterModels(list, kinds) {
  const kindTitle = Object.fromEntries(kinds.map((k) => [k.id, k.title]));
  const out = [
    "---",
    'title: "Summer Router models and prices"',
    'sidebarTitle: "Models and prices"',
    `description: ${fm(`Every model a game can use through Summer Router, with its price per unit. ${list.billing}`)}`,
    'icon: "tags"',
    'mode: "wide"',
    "generated: true",
    "generator: scripts/api",
    "---",
    "",
    banner("GET /v1/router/models"),
    "",
    "This page is generated from `GET https://api.summer.games/v1/router/models`, public and with no sign-in: the same list Summer Router meters calls with. Pick the default text and image model per game, and a model per character, on the game's **Summer Router** tab in Studio.",
    "",
  ];
  for (const kind of kinds) {
    const rows = list.models.filter((m) => m.capability === kind.id);
    if (!rows.length) continue;
    out.push(`## ${kind.title}`, "", "| Model | Id | Price | Status |", "|---|---|---|---|");
    for (const m of [...rows].sort((a, b) => Number(b.default) - Number(a.default) || a.display_name.localeCompare(b.display_name))) {
      out.push(`| ${cell(m.display_name)}${m.default ? " (default)" : ""} | ${code(m.id)} | ${m.prices.map(priceLine).join("<br />")} | ${m.status === "available" ? "Available" : "Coming soon"} |`);
    }
    out.push("");
  }
  void kindTitle;
  return out.join("\n");
}

