const ROOT = join(HERE, "..", "..");
const CHECK = process.argv.includes("--check");
const BASE = "skills";
const CATALOG_PAGE = "mcp/skills.mdx";
const TAB = "Skills";
const REPO_URL = "https://github.com/SummerEngine/summer/blob/main/library/skills";
const START = "{/* skills:catalog:start — generated by scripts/skills/generate.mjs from the skill library. Do not edit by hand. */}";
const END = "{/* skills:catalog:end */}";

