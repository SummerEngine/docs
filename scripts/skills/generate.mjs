#!/usr/bin/env node
/**
 * Render the Summer skill library as docs pages from the pinned input in
 * scripts/skills/sources/skills.json (zero dependencies, no network).
 *
 *   node scripts/skills/generate.mjs           write pages, the catalog and the Skills tab in docs.json
 *   node scripts/skills/generate.mjs --check   fail if anything on disk differs (CI)
 *
 * Pages:
 *   skills/<slug>                one page per skill: its SKILL.md, when to use it, how to install it
 *   skills/<slug>/<file>         the skill's supporting files (references, building blocks)
 *   mcp/skills                   the catalog block between the skills:catalog markers
 *
 * The source of truth is library/skills in SummerEngine/summer. To refresh the
 * input, run scripts/skills/sync.mjs; never edit the pages.
 */

